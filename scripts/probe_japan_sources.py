#!/usr/bin/env python3
"""Read-only live source probe for the Japanese first-party collection pilot.

Run on a GitHub-hosted runner, which can reach the first-party sites. No PRs,
repository changes, or articles are generated by this probe.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import sys

import yaml

from collect_intelligence_candidates import fetch_source, parse_xml_feed
from official_html_sources import parse_html_listing

ROOT = Path(__file__).resolve().parents[1]
SOURCE_IDS = (
    "nict-security-press",
    "ipa-security-alerts",
    "jpcert-alerts-jp",
    "nco-security-news",
)


def probe(config: Path, timeout: int) -> tuple[list[tuple[str, int, str]], bool]:
    registry = yaml.safe_load(config.read_text(encoding="utf-8"))
    by_id = {s["id"]: s for s in registry["sources"]}
    results: list[tuple[str, int, str]] = []
    ok = True

    for source_id in SOURCE_IDS:
        source = by_id.get(source_id)
        if not source or not source.get("enabled"):
            results.append((source_id, 0, "missing or disabled"))
            ok = False
            continue
        try:
            payload = fetch_source(source, timeout)
            if source["type"] == "rss":
                records = parse_xml_feed(payload, source)
            elif source["type"] == "html_listing":
                records = parse_html_listing(payload, source)
            else:
                raise ValueError(f"unsupported type: {source['type']}")
            count = len(records)
            if not count and source["type"] == "html_listing":
                # Minimal public-site diagnostics to identify charset / JS-only markup.
                from official_html_sources import Links, DATE_JP, plain
                raw_head = payload[:350].decode("ascii", errors="replace").replace("\n", " ")
                decoded = payload.decode("utf-8-sig", errors="replace")
                links = Links(decoded).links
                print(f"HTML debug {source_id}: {len(payload)} bytes, "
                      f"{len(links)} links, {len(DATE_JP.findall(plain(decoded)))} dates")
                print(f"HTML header preview: {raw_head}")
                for link in links[:5]:
                    print(f"HTML link: {link['href'][:140]} / {link['text'][:70]}")
                import re
                scripts = re.findall(r"<script[^>]+src=['\"]([^'\"]+)", decoded)
                print(f"HTML scripts ({len(scripts)}): " + ", ".join(scripts[-12:]))
                print("HTML tail: " + re.sub(r"\s+", " ", decoded[-1800:]))
                if source_id == "nco-security-news":
                    try:
                        from urllib.parse import urljoin
                        script_bytes = fetch_source({"url": urljoin(source["url"], "/js/app.js")}, timeout)
                        javascript = script_bytes.decode("utf-8", errors="replace")
                        print("NCO app.js bytes:", len(script_bytes))
                        for term in ("fetch(", ".json", "/api/", "news/list", "newsList"):
                            matches = list(re.finditer(re.escape(term), javascript, flags=re.I))
                            print(f"NCO script term {term}: {len(matches)} match(es)")
                            for match in matches[:3]:
                                print("NCO script context:", javascript[max(0, match.start()-90):match.end()+130].replace("\\n", " "))
                    except Exception as exc:
                        print("NCO app.js probe failed:", type(exc).__name__, str(exc)[:150])
            status = "ok" if count else "no items parsed (verify markup / feed)"
            ok = ok and count > 0
            results.append((source_id, count, status))
            if source_id == "nict-security-press" and not any(
                "/press/2026/10/13-1.html" in str(item["url"])
                for item in records
            ):
                print("NICT A2B regression notice: example no longer in listing; verify coverage manually.")
        except Exception as exc:
            results.append((source_id, 0, f"{type(exc).__name__}: {exc}"))
            ok = False

    return results, ok


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", type=Path, default=ROOT / "config/intelligence_sources.yml")
    ap.add_argument("--timeout", type=int, default=20)
    args = ap.parse_args()
    results, ok = probe(args.config, args.timeout)
    lines = [
        "### Japanese first-party source live probe",
        "",
        "| Source | Parsed items | Status |",
        "| --- | ---: | --- |",
    ]
    for source, count, status in results:
        lines.append(f"| {source} | {count} | {status.replace('|', '/')} |")
    report = "\n".join(lines) + "\n"
    print(report)
    import os
    summary = os.getenv("GITHUB_STEP_SUMMARY")
    if summary:
        with open(summary, "a", encoding="utf-8") as fh:
            fh.write(report)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
